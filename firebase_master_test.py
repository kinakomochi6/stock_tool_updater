        if data["EPS"] > 0 and data["配当利回り_pct"] > 0 and fb.get("price", 0) > 0:
            div_per_share = fb.get("price") * (data["配当利回り_pct"] / 100)
            data["配当性向_pct"] = round((div_per_share / data["EPS"]) * 100, 1)

        return data 
