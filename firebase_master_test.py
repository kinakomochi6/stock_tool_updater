def build_bs_warnings(summary, totals, gap_diagnostics=None, reported_other_values=None):
    warnings_list = []

    def add_total_warning(label, total, subtotal):
        if not total or not subtotal:
            return
        diff = total - subtotal
        threshold = max(abs(total) * 0.01, 1_000_000_000)
        if abs(diff) > threshold:
            warnings_list.append(f"{label}: 合計整合性に差があります ({diff / 1e8:,.1f}億円)")

    add_total_warning(
        "資産合計 vs 流動資産+固定資産",
        totals.get("Assets", 0),
        totals.get("CurrentAssets", 0) + totals.get("NonCurrentAssets", 0),
    )
    add_total_warning(
        "負債合計 vs 流動負債+固定負債",
        totals.get("Liabilities", 0),
        totals.get("CurrentLiabilities", 0) + totals.get("NonCurrentLiabilities", 0),
    )
    add_total_warning(
        "資産合計 vs 負債合計+純資産合計",
        totals.get("Assets", 0),
        totals.get("Liabilities", 0) + totals.get("NetAssets", 0),
    )

    if gap_diagnostics:
        for key, info in gap_diagnostics.items():
            total = info.get("total", 0)
            gap = info.get("gap", 0)
            reported = (reported_other_values or {}).get(key)
            threshold = max(abs(total) * 0.03, 1_000_000_000)
            if reported not in (None, 0):
                delta = info.get("delta_from_reported", gap - reported)
                if total and abs(delta) > threshold:
                    warnings_list.append(f"{key}: 内訳の未分類差額が大きいです ({delta / 1e8:,.1f}億円)")
            elif total and abs(gap) > threshold:
                warnings_list.append(f"{key}: 合計との差額補完が大きいです ({gap / 1e8:,.1f}億円)")

    for key in OTHER_CATEGORIES:
        val = summary.get(key, 0)
        basis = totals.get("Assets", 0) or 1
        if val < 0 and abs(val) > abs(basis) * 0.03:
            warnings_list.append(f"{key}: その他項目が大きなマイナスです ({val / 1e8:,.1f}億円)")

    return warnings_list

def analyze_bs_xbrl(doc_id, debug=False):
    url = f"https://disclosure.edinet-fsa.go.jp/api/v2/documents/{doc_id}"
    params = {"type": 1, "Subscription-Key": EDINET_API_KEY}
    try: 
        res = requests.get(url, params=params, timeout=10)
        if res.status_code != 200: return None
        z_data = io.BytesIO(res.content)
    except: return None
    
    summary = {k: 0 for k in DISPLAY_ORDER}
    totals = {"Assets":0, "CurrentAssets":0, "NonCurrentAssets":0, "Liabilities":0, "CurrentLiabilities":0, "NonCurrentLiabilities":0, "NetAssets":0}

    with zipfile.ZipFile(z_data) as z:
        xbrl_file = next((n for n in z.namelist() if n.endswith(".xbrl") and "PublicDoc" in n), None)
        if not xbrl_file: return None
        
        with z.open(xbrl_file) as f:
            try: soup = BeautifulSoup(f, 'lxml-xml')
            except: soup = BeautifulSoup(f, 'html.parser')

            doc_type = "J-GAAP"
            # Fast check using raw string
            f.seek(0)
            raw_text = f.read().decode('utf-8').lower()
            if 'ifrs-full:' in raw_text or 'ifrs:' in raw_text or 'jpigp_cor:' in raw_text: doc_type = "IFRS"
            elif 'us-gaap:' in raw_text: doc_type = "US GAAP"
            
            dei = soup.find(re.compile(r'.*CurrentPeriodEndDate'))
            end_date = dei.text.strip() if dei else None
            
            valid_contexts = []
            for ctx in soup.find_all(re.compile(r'.*context')):
                cid = ctx.get('id')
                if is_main_bs_context(ctx, end_date):
                    valid_contexts.append({
                        "id": cid,
                        "score": get_context_score(cid, ctx),
                        "members": [m.text for m in ctx.find_all(re.compile(r'.*explicitMember'))],
                    })
            
            # 各候補で実際に何個タグが取れるか試してみて、最もヒット数が多いものを採用する
            # ※高速化のため、すべての要素を一度だけ探索して contextRef ごとにまとめる
            elements_by_ctx = {}
            for el in soup.find_all():
                ctx_ref = el.get('contextRef')
                if ctx_ref:
                    elements_by_ctx.setdefault(ctx_ref, []).append(el)

            best_rank = (-1, -1)
            best_res = (summary, totals, {}, {})
            best_cid = None
            debug_contexts = []
            
            for ctx_info in valid_contexts:
                cid = ctx_info["id"]
                temp_summary = {k: 0 for k in DISPLAY_ORDER}
                temp_totals = {k: 0 for k in totals}
                hits = 0
                
                raw_tags = {}
                raw_tag_candidates = {}
                applied_tags = []
                skipped_tags = []
                elements = elements_by_ctx.get(cid, [])
                for el in elements:
                    val = parse_xbrl_number(el.text)
                    if val is None:
                        continue
                    tag = get_tag_name(el)
                    raw_tag_candidates.setdefault(tag, []).append({
                        "value": val,
                        "unitRef": el.get("unitRef"),
                        "decimals": el.get("decimals"),
                    })
                    raw_tags[tag] = val
                    
                    total_key = TOTAL_TAG_LOOKUP.get(tag)
                    if total_key:
                        temp_totals[total_key] = max(temp_totals[total_key], val)
                
                for tag, val in raw_tags.items():
                    if tag in TAG_MAPPING:
                        skip_reason = should_skip_item_tag(tag, raw_tags)
                        if skip_reason:
                            skipped_tags.append({"tag": tag, "value": val, "reason": skip_reason})
                            continue
                        action = apply_mapped_tag(temp_summary, tag, val)
                        applied_tags.append({"tag": tag, "category": TAG_MAPPING[tag], "value": val, "action": action})
                            
                        hits += 1

                apply_derived_net_tag_pairs(temp_summary, raw_tags, applied_tags)
                
                total_completeness = sum(1 for v in temp_totals.values() if v != 0)
                rank = (ctx_info["score"] + total_completeness * 80, hits)
                debug_contexts.append({
                    "id": cid,
                    "context_score": ctx_info["score"],
                    "rank": rank,
                    "hits": hits,
                    "total_completeness": total_completeness,
                    "members": ctx_info["members"],
                    "totals": temp_totals,
                    "duplicate_tags": {k: v for k, v in raw_tag_candidates.items() if len(v) > 1},
                    "applied_tags": applied_tags if debug else [],
                    "skipped_tags": skipped_tags if debug else [],
                })
                
                if rank > best_rank:
                    best_rank = rank
                    best_cid = cid
                    best_res = (temp_summary, temp_totals, raw_tags, raw_tag_candidates)
            
            summary, totals, best_raw_tags, best_raw_tag_candidates = best_res
            diagnostics = {
                "doc_id": doc_id,
                "doc_type": doc_type,
                "end_date": end_date,
                "selected_context": best_cid,
                "selected_rank": best_rank,
                "contexts": debug_contexts,
                "duplicate_tags_in_selected_context": {k: v for k, v in best_raw_tag_candidates.items() if len(v) > 1},
            }

    if summary["流動_受取手形"] > 0 or summary["流動_売掛金"] > 0:
        summary["流動_受取手形・売掛金(合算)"] = 0

    if totals["NonCurrentAssets"] == 0 and totals["Assets"] != 0:
        totals["NonCurrentAssets"] = totals["Assets"] - totals["CurrentAssets"]
    if totals["NonCurrentLiabilities"] == 0 and totals["Liabilities"] != 0:
        totals["NonCurrentLiabilities"] = totals["Liabilities"] - totals["CurrentLiabilities"]

    reported_other_values = {key: summary.get(key, 0) for key in OTHER_CATEGORIES}
    gap_diagnostics = {}

    def calc_gap(p, t, o):
        # Totals=0ならサマリに詳細タグが取れているとしても差引計算をしない(歪みを防ぐ)
        if totals[t] == 0:
            summary[o] = 0
            gap_diagnostics[o] = {"total_key": t, "total": 0, "subtotal": 0, "gap": 0, "reason": "total_missing"}
            return
        s = sum(summary[k] for k in summary if k.startswith(p) and k != o)
        gap = totals[t] - s
        reported = reported_other_values.get(o, 0)
        if reported != 0:
            summary[o] = reported
            source = "reported_other_tag"
        else:
            summary[o] = gap
            source = "computed_gap"
        gap_diagnostics[o] = {
            "total_key": t,
            "total": totals[t],
            "subtotal": s,
            "gap": gap,
            "reported": reported,
            "selected": summary[o],
            "selected_source": source,
            "delta_from_reported": gap - reported if reported != 0 else gap,
        }
    
    calc_gap("流動_", "CurrentAssets", "流動_その他流動資産")
    # 非流動資産の「その他」も同様
    if totals["NonCurrentAssets"] != 0:
        sum_fixed = sum(summary[k] for k in summary if (k.startswith("有形_") or k.startswith("無形_") or k.startswith("投資_")) and k != "投資_その他固定資産")
        gap = totals["NonCurrentAssets"] - sum_fixed
        reported = reported_other_values.get("投資_その他固定資産", 0)
        if reported != 0:
            summary["投資_その他固定資産"] = reported
            source = "reported_other_tag"
        else:
            summary["投資_その他固定資産"] = gap
            source = "computed_gap"
        gap_diagnostics["投資_その他固定資産"] = {
            "total_key": "NonCurrentAssets",
            "total": totals["NonCurrentAssets"],
            "subtotal": sum_fixed,
            "gap": gap,
            "reported": reported,
            "selected": summary["投資_その他固定資産"],
            "selected_source": source,
            "delta_from_reported": gap - reported if reported != 0 else gap,
        }
    calc_gap("流負_", "CurrentLiabilities", "流負_その他流動負債")
    calc_gap("固負_", "NonCurrentLiabilities", "固負_その他固定負債")
    if totals["NetAssets"] != 0:
        sum_net = sum(summary[k] for k in summary if k.startswith("純資_") and k != "純資_その他純資産")
        gap = totals["NetAssets"] - sum_net
        reported = reported_other_values.get("純資_その他純資産", 0)
        if reported != 0:
            summary["純資_その他純資産"] = reported
            source = "reported_other_tag"
        else:
            summary["純資_その他純資産"] = gap
            source = "computed_gap"
        gap_diagnostics["純資_その他純資産"] = {
            "total_key": "NetAssets",
            "total": totals["NetAssets"],
            "subtotal": sum_net,
            "gap": gap,
            "reported": reported,
            "selected": summary["純資_その他純資産"],
            "selected_source": source,
            "delta_from_reported": gap - reported if reported != 0 else gap,
        }
    else:
        summary["純資_その他純資産"] = 0
        gap_diagnostics["純資_その他純資産"] = {"total_key": "NetAssets", "total": 0, "subtotal": 0, "gap": 0, "reason": "total_missing"}

    bs_warnings = build_bs_warnings(summary, totals, gap_diagnostics, reported_other_values)
    if debug:
        known_numeric_tags = set(TAG_MAPPING) | set(TOTAL_TAG_LOOKUP)
        unmapped_numeric_tags = [
            {"tag": tag, "value_oku": round(val / 100000000, 3)}
            for tag, val in sorted(best_raw_tags.items(), key=lambda item: abs(item[1]), reverse=True)
            if tag not in known_numeric_tags and abs(val) >= 100000000
        ]
        note_only_unmapped_tags = [
            item for item in unmapped_numeric_tags
            if any(pattern in item["tag"] for pattern in NOTE_ONLY_TAG_PATTERNS)
        ]
        mapping_candidate_unmapped_tags = [
            item for item in unmapped_numeric_tags
            if item not in note_only_unmapped_tags
        ]
        diagnostics["gap_diagnostics"] = gap_diagnostics
        diagnostics["warnings"] = bs_warnings
        diagnostics["reported_other_values_oku"] = {
            k: round(v / 100000000, 3) for k, v in reported_other_values.items() if v != 0
        }
        diagnostics["other_gap_delta_oku"] = {
            k: round(info.get("delta_from_reported", 0) / 100000000, 3)
            for k in OTHER_CATEGORIES
            for info in [gap_diagnostics.get(k, {})]
            if info.get("delta_from_reported", 0) != 0
        }
        diagnostics["unmapped_numeric_tags_over_1oku"] = unmapped_numeric_tags[:100]
        diagnostics["note_only_unmapped_tags_over_1oku"] = note_only_unmapped_tags[:100]
        diagnostics["mapping_candidate_unmapped_tags_over_1oku"] = mapping_candidate_unmapped_tags[:100]
        diagnostics["summary_nonzero_oku"] = {k: round(v / 100000000, 3) for k, v in summary.items() if v != 0}
        diagnostics["totals_oku"] = {k: round(v / 100000000, 3) for k, v in totals.items()}
        return summary, totals, doc_type, best_raw_tags, diagnostics
    
    return summary, totals, doc_type, best_raw_tags


# --- 解析用ヘルパー関数群 ---
def normalize_str(obj):
    if obj is None: return ""
    return unicodedata.normalize('NFKC', str(obj)).replace(' ', '').replace('\n', '').replace('\u3000', '')

def get_valid_number(text):
    if pd.isna(text) or text is None: return None
    text_str = str(text)
    
    # 改行や空白で区切ってブロックごとに評価 (1869のようなHTML重複対策)
    blocks = re.split(r'[\n\s\u3000]+', text_str.strip())
    
    for block in blocks:
        normalized = unicodedata.normalize('NFKC', block).replace('△', '-').replace('▲', '-')
        normalized = re.sub(r'※\d+', '', normalized)
        normalized = re.sub(r'\(注\d*\)', '', normalized)
        
        clean_text = re.sub(r'[^\d\.\-]', '', normalized)
        try:
            if clean_text and re.fullmatch(r'-?\d+(\.\d+)?', clean_text):
                val = float(clean_text)
                if abs(val) < 10 and val.is_integer(): continue
                return val
        except: pass

    return None

def detect_unit(text):
    text = normalize_str(text)
    if "単位:百万円" in text or "単位：百万円" in text or "(百万円)" in text or "（百万円）" in text: return 1000000
    if "単位:千円" in text or "単位：千円" in text or "(千円)" in text or "（千円）" in text: return 1000
    if "単位:円" in text or "単位：円" in text: return 1
    return 1000000 

def resolve_sum_or_max(values):
    if not values: return 0
    if len(values) == 1: return values[0]
    total_sum = sum(values)
    max_val = max(values)
    rest_sum = total_sum - max_val
    if rest_sum > 0 and abs(max_val - rest_sum) / max_val < 0.05: return max_val
    return total_sum

def analyze_single_table(tbl_soup, prev_text):
    unit = detect_unit(tbl_soup.get_text())
    if unit == 1000000: unit = detect_unit(prev_text)

    try:
        dfs = pd.read_html(io.StringIO(str(tbl_soup)), header=None)
        if not dfs: return 0, 0
        df = dfs[0]
    except: return 0, 0

    rows, cols = df.shape
    if rows < 2 or cols < 2: return 0, 0

    target_col_indices = []
    col_headers = ["".join([normalize_str(df.iloc[r, c]) for r in range(min(5, rows))]) for c in range(cols)]

    for c in range(cols):
        h_text = col_headers[c]
        if "当" in h_text and any(x in h_text for x in ["連結", "事業", "年度", "期"]):
            if "前期" not in h_text and "期首" not in h_text:
                target_col_indices.append(c)
    
    if not target_col_indices:
        for c in range(cols - 1, 0, -1):
            if any(x in col_headers[c] for x in ["前連結", "前事業", "前期", "増減"]): continue
            for r in range(rows):
                if get_valid_number(df.iloc[r, c]) is not None:
                    target_col_indices.append(c)
                    break 
            if target_col_indices: break

    if not target_col_indices: return 0, 0
    target_col = target_col_indices[-1]

    found_books, found_markets = [], []
    for r in range(rows):
        row_label = "".join([normalize_str(df.iloc[r, c]) for c in range(target_col)])
        val = get_valid_number(df.iloc[r, target_col])
        if val is None: continue

        is_book_row = False
        if "期末" in row_label and ("残高" in row_label or "計上額" in row_label): is_book_row = True
        elif "貸借対照表計上額" in row_label or "帳簿価額" in row_label: is_book_row = True

        if is_book_row and any(x in row_label for x in ["期首", "増減", "償却", "損益"]): is_book_row = False
        if is_book_row and "期首" not in row_label: found_books.append(val)
        if "時価" in row_label: found_markets.append(val)

    return resolve_sum_or_max(found_books) * unit, resolve_sum_or_max(found_markets) * unit

# ★【追加】有価証券の「取得原価を超えるもの」の差額を取得する関数
def analyze_securities_table(tbl_soup, prev_text):
    unit = detect_unit(tbl_soup.get_text())
    if unit == 1000000: unit = detect_unit(prev_text)

    try:
        dfs = pd.read_html(io.StringIO(str(tbl_soup)), header=None)
        if not dfs: return 0
        df = dfs[0]
    except: return 0

    rows, cols = df.shape
    if rows < 2 or cols < 2: return 0

    is_valid_table = False
    diff_col_idx = -1
    for r in range(rows):
        row_values = []
        for c in range(cols):
            v = get_valid_number(df.iloc[r, c])
            if v is not None: row_values.append((c, v))
        
        # 3つの値 A, B, C があり、 A - B = C が成り立つ組み合わせを探す
        for i in range(len(row_values)):
            for j in range(len(row_values)):
                for k in range(len(row_values)):
                    if i == j or j == k or i == k: continue
                    ci, vi = row_values[i]; cj, vj = row_values[j]; ck, vk = row_values[k]
                    if vk > 0 and abs(vi - vj - vk) < 5:
                        is_valid_table = True
                        diff_col_idx = ck
                        break
                if is_valid_table: break
            if is_valid_table: break
        if is_valid_table: break
    
    if not is_valid_table:
        diff_col_idx = -1
        for c in range(cols):
            col_text = "".join([normalize_str(df.iloc[r, c]) for r in range(min(5, rows))])
            if any(x in col_text for x in ["差額", "評価差額", "評価益", "含み損益", "z"]): 
                diff_col_idx = c
                break
        if diff_col_idx == -1:
            for c in range(cols):
                for r in range(min(10, rows)):
                    norm_val = normalize_str(df.iloc[r, c])
                    if any(x in norm_val for x in ["差額", "評価差額", "評価益", "含み損益", "z"]):
                        diff_col_idx = c
                        break
                if diff_col_idx != -1: break
    
    if diff_col_idx == -1: return 0
    if not is_valid_table and diff_col_idx <= 1: return 0

    found_values = []
    in_exceed_section = False

    for r in range(rows):
        row_label = "".join([normalize_str(df.iloc[r, c]) for c in range(diff_col_idx)])

        # 1行目はラベルにかかわらず「超えるもの」である可能性が高い（特に mojibake 時）
        is_matched = any(x in row_label for x in ["超える", "超過", "プラス"])
        if is_matched:
            in_exceed_section = True
        elif any(x in row_label for x in ["超えない", "以下", "合計", "マイナス"]):
            in_exceed_section = False  
        elif r == 0 and len(found_values) == 0: 
            # バックアップ：最初の数行でまだ何も見つかっていなければ、暫定的に True にしてみる
            in_exceed_section = True

        if in_exceed_section:
            val = get_valid_number(df.iloc[r, diff_col_idx])
            if val is not None and val > 0:
                found_values.append(val)
                # 一度値が見つかったら、次の行が合計や「超えない」なら in_exceed_section を False にする
                # ただし、3202のように1行しかない場合はそのまま終わる
    
    # 合計値が混ざっているのを防ぐため、resolve_sum_or_max で調整
    return resolve_sum_or_max(found_values) * unit

