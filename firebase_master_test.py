def parse_xbrl_number(text):
    text_str = text.strip()
    if not re.match(r'^-?[\d\.]+$', text_str):
        return None
    try:
        return int(float(text_str))
    except Exception:
        return None

def get_context_score(cid, ctx):
    score = 0
    cid_text = cid or ""
    members = [m.text for m in ctx.find_all(re.compile(r'.*explicitMember'))]
    if "CurrentYear" in cid_text or "Current" in cid_text:
        score += 200
    if "Prior" in cid_text:
        score -= 500
    if "NonConsolidated" in cid_text:
        score -= 120
    if "Consolidated" in cid_text and "NonConsolidated" not in cid_text:
        score += 120
    if any("NonConsolidatedMember" in m for m in members):
        score -= 120
    if any("ConsolidatedMember" in m for m in members):
        score += 120
    if any("Axis" in m or "Member" in m for m in members):
        score -= 20 * len(members)
    return score

def is_main_bs_context(ctx, end_date):
    cid = ctx.get('id')
    instant = ctx.find(re.compile(r'.*instant'))
    if not cid or not instant:
        return False
    if end_date and instant.text.strip() != end_date:
        return False

    members = ctx.find_all(re.compile(r'.*explicitMember'))
    for member in members:
        text = member.text
        if "ConsolidatedMember" not in text and "NonConsolidatedMember" not in text:
            return False
    return True

def _taxonomy_sibling_lines(
    tag, candidate_siblings, taxonomy_relationships, selected_context=None,
):
    is_nonconsolidated = "NonConsolidated" in (selected_context or "")
    grouped_children = {}
    for edge in taxonomy_relationships or []:
        if edge.get("link_type") != "calculation":
            continue
        role = edge.get("role", "")
        if is_nonconsolidated and _taxonomy_role_is_consolidated(role):
            continue
        if not is_nonconsolidated and (
            _taxonomy_role_is_nonconsolidated(role)
            or _taxonomy_role_is_standalone_statement(role)
        ):
            continue
        grouped_children.setdefault(edge.get("parent"), set()).add(
            edge.get("child")
        )
    siblings = set()
    for children in grouped_children.values():
        if tag in children:
            siblings.update(candidate_siblings & children)
    return siblings


