def get_financial_data(code):
    ticker, price = get_valid_ticker_and_price(code)
    fb = {}
    if not ticker or price == 0:
        # 名証などYahooで取得できない銘柄はみんかぶ・Yahooファイナンスからスクレイピング
        fb = scrape_fallback_data(code)
        price = fb.get("price", 0)
        
    data = empty_financial_data(price, fb.get("mcap_oku", 0))
    
    if not ticker:
        # フォールバック時: 独自に取得した指標をセット
        data["配当利回り_pct"] = fb.get("div_yield", 0)
        data["EPS"] = fb.get("eps", 0)
        data["PBR"] = fb.get("pbr", 0)
        data["PER"] = fb.get("per", 0)
        data["ROE_pct"] = fb.get("roe", 0)
        
        # 純資産(億)の計算: みんかぶの時価総額 / PBR (※PBRが取得できている場合)
        if data["PBR"] > 0 and data["時価総額_億"] > 0:
            data["純資産_億"] = round(data["時価総額_億"] / data["PBR"], 1)
        elif fb.get("bps", 0) > 0 and fb.get("price", 0) > 0 and data["時価総額_億"] > 0:
            # 株式数 = 時価総額 / 株価
            shares = (data["時価総額_億"] * 100000000) / fb.get("price")
            data["純資産_億"] = round((fb.get("bps") * shares) / 100000000, 1)

        # 配当性向の計算: 1株配当 / EPS
        if data["EPS"] > 0 and data["配当利回り_pct"] > 0 and fb.get("price", 0) > 0:
            div_per_share = fb.get("price") * (data["配当利回り_pct"] / 100)
            data["配当性向_pct"] = round((div_per_share / data["EPS"]) * 100, 1)

        return data 
    try: info = ticker.info
    except: info = {}

    if data["株価"] == 0: data["株価"] = info.get('currentPrice', 0)
    shares = info.get('sharesOutstanding', 0)
    market_cap_oku = info.get('marketCap', 0)
    if market_cap_oku == 0 and shares > 0 and data["株価"] > 0:
        market_cap_oku = data["株価"] * shares
    data["時価総額_億"] = round(market_cap_oku / 100000000, 1)
    
    div_rate = info.get('dividendRate', 0)
    div_yield = (div_rate / data["株価"] * 100) if data["株価"] > 0 else 0
    if div_yield == 0: div_yield = info.get('dividendYield', 0) * 100
    if div_yield: data["配当利回り_pct"] = round(div_yield, 2)

    if info.get('trailingEps'): data["EPS"] = round(info.get('trailingEps'), 2)
    if info.get('priceToBook'): data["PBR"] = round(info.get('priceToBook'), 2)
    if info.get('trailingPE'): data["PER"] = round(info.get('trailingPE'), 2)
    payout = info.get('payoutRatio', 0)
    data["配当性向_pct"] = round(payout * 100, 1) if payout else 0
    roe = info.get('returnOnEquity', 0)
    if roe: data["ROE_pct"] = round(roe * 100, 2)
    if data["PBR"] > 0: data["純資産_億"] = round(data["時価総額_億"] / data["PBR"], 1)

    try:
        hist_10y = ticker.history(period="10y")
        if not hist_10y.empty and shares > 0:
            data["10年平均時価総額_億"] = round((hist_10y['Close'].mean() * shares) / 100000000, 1)
        divs = ticker.dividends
        if not divs.empty:
            divs.index = divs.index.tz_localize(None)
            yearly = divs.resample('YE').sum().tail(11)
            if len(yearly) > 1:
                pct = yearly.pct_change().dropna()
                data["10年増配率_pct"] = round((pct > 0).sum() / len(pct) * 100, 1)
                data["10年減配率_pct"] = round((pct < 0).sum() / len(pct) * 100, 1)
                
        financials = ticker.financials
        cashflow = ticker.cashflow
        if not financials.empty:
            cols = financials.columns[:4] 
            years_count = len(cols)
            
            avg_mc_4y = data["時価総額_億"]
            hist_4y = hist_10y.tail(int(365 * 4 * 0.7)) if not hist_10y.empty else pd.DataFrame()
            if not hist_4y.empty and shares > 0:
                avg_mc_4y = float((hist_4y['Close'].mean() * shares) / 100000000)

            op_incomes, ord_incomes, net_incomes, buybacks, total_returns, per_history = [], [], [], [], [], []
            
            for date in cols:
                op = np.nan
                for key in ['Operating Income', 'Operating Revenue']:
                    if key in financials.index and pd.notna(financials.loc[key, date]):
                        op = financials.loc[key, date]
                        break
                if pd.notna(op): op_incomes.append(op)
                
                ord_inc = np.nan
                for key in ['Pretax Income', 'Income Before Tax']:
                    if key in financials.index and pd.notna(financials.loc[key, date]):
                        ord_inc = financials.loc[key, date]
                        break
                if pd.notna(ord_inc): ord_incomes.append(ord_inc)
                
                net = np.nan
                if 'Net Income' in financials.index and pd.notna(financials.loc['Net Income', date]):
                    net = financials.loc['Net Income', date]
                if pd.notna(net): net_incomes.append(net)
                
                year_eps = np.nan
                if 'Basic EPS' in financials.index and pd.notna(financials.loc['Basic EPS', date]):
                    year_eps = financials.loc['Basic EPS', date]
                try:
                    year_str = str(date.year)
                    if not hist_10y.empty and year_str in hist_10y.index.strftime('%Y'):
                        if pd.notna(year_eps) and year_eps > 0:
                            per_history.append(hist_10y.loc[year_str]['Close'].mean() / year_eps)
                except: pass

                bb, dp = 0, 0
                if not cashflow.empty and date in cashflow.columns:
                    for key in ['Repurchase Of Capital Stock', 'Common Stock Repurchased']:
                        if key in cashflow.index and pd.notna(cashflow.loc[key, date]):
                            bb = abs(cashflow.loc[key, date])
                            break
                    for key in ['Cash Dividends Paid', 'Dividends Paid']:
                        if key in cashflow.index and pd.notna(cashflow.loc[key, date]):
                            dp = abs(cashflow.loc[key, date])
                            break
                buybacks.append(bb)
                total_returns.append(bb + dp)
            
            if years_count > 0:
                data["4年赤字率_pct"] = round((sum(1 for x in net_incomes if x < 0) / years_count * 100), 1)
            
            data["4年平均PER_赤字除"] = round(float(np.mean(per_history)), 2) if per_history else data["PER"]
            
            avg_bb = float(np.mean(buybacks)) / 100000000 if buybacks else 0
            avg_tr = float(np.mean(total_returns)) / 100000000 if total_returns else 0
            data["4年平均自社株買い_億"] = round(avg_bb, 1)
            data["4年平均総還元額_億"] = round(avg_tr, 1)
            
            if avg_mc_4y > 0:
                data["4年自社株買い利回り_pct"] = round(avg_bb / avg_mc_4y * 100, 2)
                data["4年平均還元利回り_pct"] = round(avg_tr / avg_mc_4y * 100, 2)
            if avg_tr > 0: 
                data["4年自社株買い比率_pct"] = round(avg_bb / avg_tr * 100, 1)
            
            if op_incomes: data["4年最低営業利益_億"] = round(float(min(op_incomes)) / 100000000, 1)
            if ord_incomes: data["4年最低経常利益_億"] = round(float(min(ord_incomes)) / 100000000, 1)
    except: pass
    return data

