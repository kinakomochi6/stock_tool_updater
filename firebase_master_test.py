def initialize_firebase():
    if not firebase_admin._apps:
        if FIREBASE_CREDENTIALS:
            cred = credentials.Certificate(json.loads(FIREBASE_CREDENTIALS))
        else:
            cred = credentials.Certificate(FIREBASE_KEY)
        firebase_admin.initialize_app(cred)
    return firestore.client()

def parse_codes_arg(codes_arg):
    if not codes_arg:
        return None
    codes = re.findall(r'(?<!\d)\d{4}(?!\d)', str(codes_arg))
    if not codes:
        raise ValueError(f"銘柄コードを4桁で指定してください: {codes_arg}")
    return sorted(set(codes))

def validate_tag_mapping():
    unknown_categories = sorted(set(TAG_MAPPING.values()) - set(DISPLAY_ORDER))
    if unknown_categories:
        joined = ", ".join(unknown_categories)
        raise ValueError(f"TAG_MAPPINGにDISPLAY_ORDER未定義のカテゴリがあります: {joined}")

def get_all_listed_codes():
    url = "https://www.jpx.co.jp/markets/statistics-equities/misc/tvdivq0000001vg2-att/data_j.xls"
    print("JPXから上場銘柄リストを取得中...")
    try:
        res = requests.get(url, timeout=10)
        df = pd.read_excel(io.BytesIO(res.content))
        
        # ETF, REIT などを除外（普通株式のみにフィルタリング）
        invalid_markets = ["ETF・ETN", "REIT・ベンチャーファンド・カントリーファンド・インフラファンド", "出資証券"]
        df = df[~df['市場・商品区分'].isin(invalid_markets)]
        
        companies = []
        for i, row in df.iterrows():
            code = str(row['コード']).strip()
            name = str(row['銘柄名']).strip()
            market = str(row['市場・商品区分']).strip()
            sector = str(row['33業種区分']).strip()
            if len(code) >= 4:
                companies.append({"code": code[:4], "name": name, "market": market, "sector": sector})
                
        return companies
    except Exception as e:
        print(f"上場銘柄リストの取得に失敗しました: {e}")
        return []

def main():
    print("=== 全データ統合バッチ処理（原点回帰 ＆ 有価証券追加版） ===")
    
    parser = argparse.ArgumentParser(description="Stock Data Scraper")
    parser.add_argument("--total-shards", type=int, default=1, help="Total number of shards")
    parser.add_argument("--shard-index", type=int, default=0, help="Index of this shard (0 to total-shards-1)")
    parser.add_argument("--codes", type=str, default="", help="Comma or space separated stock codes. Example: --codes 7203,6758")
    parser.add_argument("--days-back", type=int, default=365, help="How many days of EDINET documents to scan")
    parser.add_argument("--debug-bs", action="store_true", help="Write B/S extraction diagnostics JSON for each processed code")
    parser.add_argument("--debug-dir", type=str, default=".", help="Directory for --debug-bs output files")
    parser.add_argument("--dry-run", action="store_true", help="Run without writing results to Firestore")
    args = parser.parse_args()

    if not EDINET_API_KEY:
        raise RuntimeError("EDINET_API_KEY が未設定です。環境変数またはGitHub Secretsに設定してください。")
    if args.total_shards < 1:
        raise ValueError("--total-shards は1以上で指定してください。")
    if args.shard_index < 0 or args.shard_index >= args.total_shards:
        raise ValueError("--shard-index は 0 以上 total-shards 未満で指定してください。")

    validate_tag_mapping()
    requested_codes = parse_codes_arg(args.codes)
    if not args.dry_run and not requested_codes and not ALLOW_FULL_FIRESTORE_WRITE:
        raise RuntimeError(
            "全件Firestore更新は安全のためブロックされました。"
            "全件更新を許可する場合は ALLOW_FULL_FIRESTORE_WRITE=1 を設定してください。"
        )
    
    # Firebase接続
    collection_ref = None
    if args.dry_run:
        print("DRY RUN: Firestoreへの保存をスキップします。")
    else:
        db = initialize_firebase()
        collection_ref = db.collection('companies')

    companies_list = get_all_listed_codes()
    
    if not companies_list:
        print("エラー: 銘柄リストが取得できなかったため、処理を終了します。")
        return

    jpx_codes = {c["code"]: c for c in companies_list}

    if requested_codes:
        companies_list = [
            jpx_codes.get(code, {"code": code, "name": "名称不明(指定銘柄)", "market": "不明", "sector": "不明"})
            for code in requested_codes
        ]
        target_codes_for_scan = requested_codes
        print(f"\n単体更新モード: {', '.join(requested_codes)} のみ更新します。")
    else:
        # 先にEdinetSearcherで過去書類をスキャンし、東証以外の銘柄を洗い出す
        target_codes_for_scan = list(jpx_codes.keys()) + ["0000"] # 確実に365日スキャンさせるためのダミーコード
    
    searcher = EdinetSearcher()
    searcher.fetch_list(target_codes_for_scan, days_back=args.days_back)
    
    if not requested_codes:
        # EDINETで見つかった全証券コードを抽出
        edinet_sec_codes = set()
        if not searcher.df_docs.empty:
            for sec in searcher.df_docs['secCode'].dropna().unique():
                sec_str = str(sec).strip()
                # 一般事業会社の証券コードは5桁で末尾が0
                if len(sec_str) == 5 and sec_str.endswith('0'):
                    edinet_sec_codes.add(sec_str[:4])
                    
        # JPXリストにないEDINET提出企業（主に地方単独上場）を追加
        added_count = 0
        for code in edinet_sec_codes:
            if code not in jpx_codes:
                companies_list.append({"code": code, "name": "名称不明(東証以外)", "market": "その他市場", "sector": "その他"})
                added_count += 1
                
        print(f"\nJPXリストにない地方上場企業などを {added_count} 社追加しました。")

    target_codes = [c["code"] for c in companies_list]
    info_dict = {c["code"]: c for c in companies_list}
    
    # 分散処理のためのスライス計算
    target_codes = sorted(target_codes)  # 順序を固定するためソート
    total_len = len(target_codes)
    
    if args.total_shards > 1 and not requested_codes:
        start_idx = total_len * args.shard_index // args.total_shards
        end_idx = total_len * (args.shard_index + 1) // args.total_shards
        target_codes = target_codes[start_idx:end_idx]
        print(f"\n分散処理が有効です: Shard {args.shard_index + 1} / {args.total_shards}")
        print(f"全体 {total_len}社のうち、{len(target_codes)}社を処理します（インデックス {start_idx}〜{end_idx-1}）")
        
    total_count = len(target_codes)
    print(f"\n取得対象銘柄数 (本Shard): {total_count}社")
    if requested_codes:
        print("※単体更新モードのため、Shard指定は無視します。")
    else:
        print("※分散処理のため、各Shardごとに並行して処理が行われます。")

    for i, code in enumerate(target_codes, 1):
        print(f"\n[{i}/{total_count}] {code} 処理中...")
        comp_info = info_dict.get(code, {})
        company_name = comp_info.get("name", "名称不明")
        market = comp_info.get("market", "")
        sector = comp_info.get("sector", "")
        
        # ★ 東証以外の企業など情報の無い銘柄は、みんかぶから企業名等を補完
        if "不明" in company_name or "東証以外" in company_name:
            try:
                url_mk = f"https://minkabu.jp/stock/{code}"
                res_mk = requests.get(url_mk, headers={'User-Agent': 'Mozilla/5.0'}, timeout=5)
                if res_mk.status_code == 200:
                    soup_mk = BeautifulSoup(res_mk.text, 'html.parser')
                    
                    # 企業名
                    t_title = soup_mk.find('title')
                    if t_title:
                        scraped_name = t_title.text.split(' (')[0].strip()
                        if scraped_name: company_name = scraped_name
                    
                    # 市場
                    m_label = soup_mk.find('div', class_='stock_label')
                    if m_label:
                        market = m_label.text.replace(chr(160), ' ').replace(str(code), '').strip()
                        
                    # 業種
                    for el in soup_mk.find_all(string=re.compile('業種')):
                        if el.strip() == "業種":
                            nx = el.parent.find_next_sibling()
                            if nx:
                                sector = nx.text.strip()
                                break
            except Exception as e:
                print(f" -> [警告] みんかぶからの情報補完に失敗しました: {e}")

        try:
            combined_data = {k: 0 for k in DISPLAY_ORDER}
            combined_data.update({
                "★企業名": company_name,
                "★市場区分": market,
                "★業種": sector,
                "★資産合計": 0, "★負債合計": 0, "★純資産合計": 0,
                "不動産_簿価_億": 0, "不動産_時価_億": 0, "不動産_含み益_億": 0, "有価証券_含み益_億": 0,
                "B/S_取得書類": "なし", "不動産_取得書類": "なし"
            })
            
            fin_data = get_financial_data(code)
            combined_data.update(fin_data)
            
            # B/S データの取得
            bs_doc_id, bs_desc, _ = searcher.find_best_bs_doc(code)
            if bs_doc_id:
                ret = analyze_bs_xbrl(bs_doc_id, debug=args.debug_bs)
                if ret:
                    bs_diagnostics = None
                    if len(ret) == 5:
                        summary, totals, doc_type, _, bs_diagnostics = ret
                        combined_data["B/S_取得書類"] = f"{bs_desc} ({doc_type})"
                    elif len(ret) == 4: # To handle new signature safely
                        summary, totals, doc_type, _ = ret
                        combined_data["B/S_取得書類"] = f"{bs_desc} ({doc_type})"
                    elif len(ret) == 3:
                        summary, totals, doc_type = ret
                        combined_data["B/S_取得書類"] = f"{bs_desc} ({doc_type})"
                    else:
                        summary, totals = ret
                        combined_data["B/S_取得書類"] = bs_desc
                        
                    for k in DISPLAY_ORDER:
                        combined_data[k] = round(summary[k] / 100000000, 3)
                    combined_data["★資産合計"] = round(totals['Assets'] / 100000000, 3)
                    combined_data["★負債合計"] = round(totals['Liabilities'] / 100000000, 3)
                    combined_data["★純資産合計"] = round(totals['NetAssets'] / 100000000, 3)

                    if bs_diagnostics:
                        warnings_text = bs_diagnostics.get("warnings", [])
                        combined_data["B/S_警告"] = warnings_text
                        os.makedirs(args.debug_dir, exist_ok=True)
                        debug_path = os.path.join(args.debug_dir, f"debug_bs_{code}.json")
                        with open(debug_path, "w", encoding="utf-8") as f:
                            json.dump(bs_diagnostics, f, ensure_ascii=False, indent=2)
                        print(f" -> [B/S診断] {debug_path} に出力しました。警告: {len(warnings_text)}件")
            
            time.sleep(2)  # API制限対策・待機
            
            # 不動産と有価証券データの取得
            re_doc_id = searcher.find_best_re_doc(code)
            if re_doc_id:
                re_sec_data = analyze_real_estate_and_securities_html(re_doc_id)
                if re_sec_data["不動産_時価_億"] > 0 or re_sec_data["不動産_簿価_億"] > 0 or re_sec_data["有価証券_含み益_億"] > 0:
                    combined_data.update(re_sec_data)
                    combined_data["不動産_取得書類"] = "有価証券報告書等より取得"

            # Firebaseへ保存
            if args.dry_run:
                print(" -> [DRY RUN] Firestore保存をスキップしました。")
            else:
                combined_data["データ最終更新日"] = firestore.SERVER_TIMESTAMP
                collection_ref.document(str(code)).set(combined_data, merge=True)
            
            print(f" -> [{company_name}] 財務 ROE: {combined_data['ROE_pct']}% / 時価総額: {combined_data['時価総額_億']}億円 / 4年平均自社株買い: {combined_data['4年平均自社株買い_億']}億円")
            print(f" -> [ B/S] 資産合計: {combined_data['★資産合計']}億円 ({combined_data['B/S_取得書類']})")
            print(f" -> [隠し資産] 不動産含み益: {combined_data['不動産_含み益_億']}億円 / 有価証券含み益: {combined_data['有価証券_含み益_億']}億円")
            
        except Exception as e:
            print(f" -> [エラー] {code} の処理中にエラーが発生しました: {e}")
            
        time.sleep(2)  # API制限対策・次の銘柄へ行く前に待機

    print("\nすべての処理が完了しました！")

if __name__ == "__main__":
    main()
