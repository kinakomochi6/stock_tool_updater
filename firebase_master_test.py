def reconcile_receivable_presentation(summary, totals, raw_tags):
    combined_category = "流動_受取手形・売掛金(合算)"
    detail_categories = {
        "流動_受取手形", "流動_売掛金", "流動_電子記録債権", "流動_契約資産",
        "流動_完成工事未収入金", "流動_完成工事未収入金・契約資産",
    }
    detail_values = {category: summary.get(category, 0) for category in detail_categories}
    combined_value = summary.get(combined_category, 0)
    separate_value = sum(detail_values.values())
    if combined_value <= 0 or separate_value <= 0:
        return None

    includes_contract_assets = any(
        tag in raw_tags for tag in COMBINED_RECEIVABLE_TAGS_WITH_CONTRACT_ASSETS
    ) or any(
        "Receivable" in tag and "ContractAsset" in tag
        for tag in raw_tags
    )
    electronic_value = summary.get("流動_電子記録債権", 0)
    contract_value = summary.get("流動_契約資産", 0)
    combined_option = combined_value + electronic_value
    if not includes_contract_assets:
        combined_option += contract_value

    current_assets = totals.get("CurrentAssets", 0)
    other_current_assets = summary.get("流動_その他流動資産", 0)
    excluded_categories = detail_categories | {combined_category, "流動_その他流動資産"}
    base_value = sum(
        value for category, value in summary.items()
        if category.startswith("流動_") and category not in excluded_categories
    )
    combined_delta = current_assets - base_value - other_current_assets - combined_option
    separate_delta = current_assets - base_value - other_current_assets - separate_value

    if current_assets:
        use_combined = abs(combined_delta) <= abs(separate_delta)
    else:
        use_combined = combined_value >= separate_value * 1.2

    if use_combined:
        summary["流動_受取手形"] = 0
        summary["流動_売掛金"] = 0
        summary["流動_完成工事未収入金"] = 0
        summary["流動_完成工事未収入金・契約資産"] = 0
        if includes_contract_assets:
            summary["流動_契約資産"] = 0
        includes_other_claims = False
        if any(tag in raw_tags for tag in COMBINED_RECEIVABLE_TAGS_WITH_OTHER_CLAIMS):
            electronic_claims = summary.get("流動_電子記録債権", 0)
            current_assets = totals.get("CurrentAssets", 0)
            if electronic_claims and current_assets:
                subtotal = sum(value for key, value in summary.items() if key.startswith("流動_"))
                delta_keep = current_assets - subtotal
                delta_remove = delta_keep + electronic_claims
                tolerance = max(abs(current_assets) * 0.0001, 1_000_000)
                if abs(delta_remove) + tolerance < abs(delta_keep):
                    summary["流動_電子記録債権"] = 0
                    includes_other_claims = True
        restored_details = []
        restored_delta_before = None
        restored_delta_after = None
        if current_assets:
            restored_delta_before = current_assets - sum(
                value for key, value in summary.items() if key.startswith("流動_")
            )
            restore_candidates = [
                (category, value)
                for category, value in detail_values.items()
                if value > 0 and summary.get(category, 0) == 0
            ]
            best_combo = None
            best_delta = restored_delta_before
            for size in range(1, len(restore_candidates) + 1):
                for combo in combinations(restore_candidates, size):
                    delta_after = restored_delta_before - sum(value for _, value in combo)
                    if abs(delta_after) < abs(best_delta):
                        best_combo = combo
                        best_delta = delta_after
            tolerance = max(abs(current_assets) * 0.0001, 1_000_000)
            if (
                best_combo
                and abs(best_delta) < abs(restored_delta_before) * 0.25
                and abs(best_delta) + tolerance < abs(restored_delta_before)
            ):
                for category, value in best_combo:
                    summary[category] = value
                    restored_details.append(category)
                restored_delta_after = best_delta
        selected = "combined"
    else:
        summary[combined_category] = 0
        selected = "separate"
        includes_other_claims = False
        restored_details = []
        restored_delta_before = None
        restored_delta_after = None

    return {
        "selected": selected,
        "combined_delta": combined_delta,
        "separate_delta": separate_delta,
        "combined_includes_contract_assets": includes_contract_assets,
        "combined_includes_other_claims": includes_other_claims,
        "restored_detail_categories": restored_details,
        "restored_delta_before": restored_delta_before,
        "restored_delta_after": restored_delta_after,
    }

def reconcile_optional_duplicate_categories(summary, totals):
    adjustments = []
    groups = {}
    for category, prefix, total_key, other_category in OPTIONAL_DUPLICATE_CATEGORIES:
        value = summary.get(category, 0)
        total = totals.get(total_key, 0)
        if value <= 0 or total == 0:
            continue
        groups.setdefault((prefix, total_key, other_category), []).append((category, value))

    for (prefix, total_key, other_category), candidates in groups.items():
        total = totals[total_key]
        reported_other = summary.get(other_category, 0)
        subtotal = sum(summary[k] for k in summary if k.startswith(prefix) and k != other_category)
        delta_before = total - subtotal - reported_other
        if delta_before >= 0:
            continue

        best_combo = None
        best_delta = delta_before
        for size in range(1, len(candidates) + 1):
            for combo in combinations(candidates, size):
                delta_after = delta_before + sum(value for _, value in combo)
                if abs(delta_after) < abs(best_delta):
                    best_combo = combo
                    best_delta = delta_after

        if best_combo and abs(best_delta) < abs(delta_before) * 0.25:
            for category, value in best_combo:
                summary[category] = 0
                adjustments.append({
                    "category": category,
                    "value": value,
                    "reason": "section_total_indicates_optional_detail_duplicate",
                    "delta_before": delta_before,
                    "delta_after": best_delta,
                })

    # Resolve broad parent/detail duplicates first, then test individually
    # ambiguous current-liability lines against the updated section balance.
    for category in REMOVE_WHEN_SECTION_FIT_IMPROVES:
        value = summary.get(category, 0)
        total = totals.get("CurrentLiabilities", 0)
        if value <= 0 or total == 0:
            continue
        other_category = "流負_その他流動負債"
        reported_other = summary.get(other_category, 0)
        subtotal = sum(
            amount for key, amount in summary.items()
            if key.startswith("流負_") and key != other_category
        )
        delta_before = total - subtotal - reported_other
        delta_after = delta_before + value
        if abs(delta_after) < abs(delta_before):
            summary[category] = 0
            adjustments.append({
                "category": category,
                "value": value,
                "reason": "section_total_indicates_ambiguous_current_detail_duplicate",
                "delta_before": delta_before,
                "delta_after": delta_after,
            })
    return adjustments


def _has_semantic_suffix(tag, marker):
    suffixes = {
        "CA": r"(?<!N)CA(?:IFRS|[A-Z]{2,8})?$",
        "NCA": r"(?:NCA|IOA)(?:IFRS|[A-Z]{2,8})?$",
        "CL": r"(?<!N)CL(?:IFRS|[A-Z]{2,8})?$",
        "NCL": r"NCL(?:IFRS|[A-Z]{2,8})?$",
        "PPE": r"PPE(?:IFRS|[A-Z]{2,8})?$",
        "IA": r"IA(?:IFRS|[A-Z]{2,8})?$",
        "EQUITY": r"(?:NA|EquityIFRS)$",
    }
    return re.search(suffixes[marker], tag) is not None


def _net_variant_exists(tag, raw_tags):
    if "Net" in tag:
        return False
    normalized = tag.replace("Net", "")
    return any(
        other != tag and "Net" in other and other.replace("Net", "") == normalized
        for other in raw_tags
    )


