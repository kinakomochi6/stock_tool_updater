def parse_taxonomy_relationships(archive):
    """Read B/S relationships and extension labels from an EDINET package."""
    concept_ids = {}
    errors = []
    parsed_files = []
    label_files = []
    relationships = []
    concept_labels = {}
    note_concepts = set()

    for name in archive.namelist():
        if "publicdoc" not in name.lower() or not name.lower().endswith(".xsd"):
            continue
        try:
            root = ET.fromstring(archive.read(name))
            for element in root.iter():
                if _xml_local_name(element.tag) != "element":
                    continue
                concept_id = element.get("id")
                concept_name = element.get("name")
                if concept_id and concept_name:
                    concept_ids[concept_id] = concept_name
        except (ET.ParseError, KeyError, OSError) as exc:
            errors.append({"file": name, "error": repr(exc)})

    for name in archive.namelist():
        lower_name = name.lower()
        link_type = next(
            (kind for suffix, kind in TAXONOMY_LINKBASE_SUFFIXES.items()
             if lower_name.endswith(suffix)),
            None,
        )
        if not link_type or "publicdoc" not in name.lower():
            continue
        try:
            root = ET.fromstring(archive.read(name))
        except (ET.ParseError, KeyError, OSError) as exc:
            errors.append({"file": name, "error": repr(exc)})
            continue

        parsed_files.append(name)
        link_element_name = f"{link_type}Link"
        arc_element_name = f"{link_type}Arc"
        for link in root.iter():
            if _xml_local_name(link.tag) != link_element_name:
                continue
            role = link.get(f"{{{XLINK_NAMESPACE}}}role", "")
            role_lower = role.lower()
            if not any(
                token in role_lower for token in ("balancesheet", "financialposition")
            ):
                continue
            is_note_role = "note" in role_lower

            locators = {}
            for child in link:
                if _xml_local_name(child.tag) != "loc":
                    continue
                label = child.get(f"{{{XLINK_NAMESPACE}}}label", "")
                href = child.get(f"{{{XLINK_NAMESPACE}}}href", "")
                concept = _taxonomy_concept_from_href(href, concept_ids)
                if label and concept:
                    locators[label] = concept

            for child in link:
                if _xml_local_name(child.tag) != arc_element_name:
                    continue
                if child.get("use") == "prohibited":
                    continue
                arcrole = child.get(f"{{{XLINK_NAMESPACE}}}arcrole", "")
                arcrole_name = _taxonomy_arcrole_name(arcrole)
                if (
                    link_type == "definition"
                    and arcrole_name not in TAXONOMY_DEFINITION_ARCROLES
                ):
                    continue
                parent = locators.get(child.get(f"{{{XLINK_NAMESPACE}}}from", ""))
                concept = locators.get(child.get(f"{{{XLINK_NAMESPACE}}}to", ""))
                if not parent or not concept or parent == concept:
                    continue
                if is_note_role:
                    note_concepts.update((parent, concept))
                    continue
                relationships.append({
                    "parent": parent,
                    "child": concept,
                    "link_type": link_type,
                    "role": role,
                    "arcrole": arcrole_name,
                    "weight": child.get("weight"),
                    "order": child.get("order"),
                    "source_file": name,
                })

    for name in archive.namelist():
        if "publicdoc" not in name.lower() or not _taxonomy_label_file(name):
            continue
        try:
            root = ET.fromstring(archive.read(name))
        except (ET.ParseError, KeyError, OSError) as exc:
            errors.append({"file": name, "error": repr(exc)})
            continue

        label_files.append(name)
        for link in root.iter():
            if _xml_local_name(link.tag) != "labelLink":
                continue
            locators = {}
            resources = {}
            for child in link:
                local_name = _xml_local_name(child.tag)
                xlink_label = child.get(f"{{{XLINK_NAMESPACE}}}label", "")
                if local_name == "loc":
                    concept = _taxonomy_concept_from_href(
                        child.get(f"{{{XLINK_NAMESPACE}}}href", ""), concept_ids,
                    )
                    if xlink_label and concept:
                        locators[xlink_label] = concept
                elif local_name == "label" and xlink_label:
                    text = "".join(child.itertext()).strip()
                    if text:
                        resources[xlink_label] = {
                            "text": text,
                            "lang": child.get("{http://www.w3.org/XML/1998/namespace}lang", ""),
                            "role": child.get(f"{{{XLINK_NAMESPACE}}}role", ""),
                            "source_file": name,
                        }
            for child in link:
                if _xml_local_name(child.tag) != "labelArc":
                    continue
                concept = locators.get(child.get(f"{{{XLINK_NAMESPACE}}}from", ""))
                resource = resources.get(child.get(f"{{{XLINK_NAMESPACE}}}to", ""))
                if concept and resource:
                    concept_labels.setdefault(concept, []).append(resource)

    unique = {}
    for item in relationships:
        key = (
            item["parent"], item["child"], item["link_type"],
            item["role"], item.get("arcrole"), item.get("weight"),
        )
        unique[key] = item
    for concept, labels in concept_labels.items():
        deduplicated = {}
        for label in labels:
            key = (label["text"], label["lang"], label["role"])
            deduplicated[key] = label
        concept_labels[concept] = list(deduplicated.values())
    return {
        "relationships": list(unique.values()),
        "files": parsed_files,
        "label_files": label_files,
        "labels": concept_labels,
        "note_concepts": sorted(note_concepts),
        "label_count": sum(len(labels) for labels in concept_labels.values()),
        "concept_id_count": len(concept_ids),
        "errors": errors,
    }


def _taxonomy_section_for_category(category):
    for section, spec in SEMANTIC_SECTION_SPECS.items():
        if category.startswith(spec["prefix"]):
            return section
    return None


def build_taxonomy_parent_index(relationships):
    parent_index = {}
    for item in relationships or []:
        parent_index.setdefault(item["child"], []).append(item)
    return parent_index


def _taxonomy_role_is_consolidated(role):
    normalized = (role or "").lower().replace("-", "")
    return "consolidated" in normalized and "nonconsolidated" not in normalized


def _taxonomy_role_is_nonconsolidated(role):
    normalized = (role or "").lower().replace("-", "")
    return "nonconsolidated" in normalized


def _taxonomy_role_is_standalone_statement(role):
    tail = (role or "").rsplit("/", 1)[-1]
    normalized = re.sub(r"[-_]", "", tail).lower()
    if "consolidated" in normalized:
        return False
    return normalized.endswith((
        "balancesheet",
        "statementoffinancialposition",
        "statementoffinancialpositionifrs",
    ))


def build_taxonomy_statement_memberships(relationships):
    """Collect concepts explicitly placed in consolidated or standalone B/S roles."""
    memberships = {"consolidated": set(), "standalone": set()}
    for edge in relationships or []:
        link_type = edge.get("link_type")
        if link_type not in {"calculation", "definition", "presentation"}:
            continue
        if link_type == "definition" and edge.get("arcrole") != "domain-member":
            continue
        role = edge.get("role", "")
        if _taxonomy_role_is_consolidated(role):
            scope = "consolidated"
        elif (
            _taxonomy_role_is_nonconsolidated(role)
            or _taxonomy_role_is_standalone_statement(role)
        ):
            scope = "standalone"
        else:
            continue
        memberships[scope].update((edge.get("parent"), edge.get("child")))
    memberships["consolidated"].discard(None)
    memberships["standalone"].discard(None)
    return memberships


def taxonomy_statement_scope_skip_reason(
    tag, selected_context, memberships, note_concepts=None,
):
    consolidated = memberships.get("consolidated", set())
    standalone = memberships.get("standalone", set())
    if (
        tag in set(note_concepts or ())
        and tag not in consolidated
        and tag not in standalone
    ):
        return "note_only_tag_skipped_for_balance_sheet"
    is_nonconsolidated = "NonConsolidated" in (selected_context or "")
    if (
        is_nonconsolidated
        and standalone
        and tag in consolidated
        and tag not in standalone
    ):
        return "consolidated_only_tag_skipped_for_standalone_statement"
    if (
        not is_nonconsolidated
        and consolidated
        and tag in standalone
        and tag not in consolidated
    ):
        return "standalone_only_tag_skipped_for_consolidated_statement"
    return None


def select_bs_totals(raw_tags, taxonomy_relationships, selected_context=None):
    """Select the highest-level reported total instead of the largest value."""
    is_nonconsolidated = "NonConsolidated" in (selected_context or "")
    calculation_children = {}
    for edge in taxonomy_relationships or []:
        if edge.get("link_type") != "calculation":
            continue
        role = edge.get("role", "")
        if is_nonconsolidated and _taxonomy_role_is_consolidated(role):
            continue
        if not is_nonconsolidated and (
            _taxonomy_role_is_nonconsolidated(role)
            or _taxonomy_role_is_standalone_statement(role)
        ):
            continue
        calculation_children.setdefault(edge.get("parent"), set()).add(
            edge.get("child")
        )

    def descendant_count(tag, candidate_tags):
        seen = set()
        pending = list(calculation_children.get(tag, ()))
        while pending:
            child = pending.pop()
            if child in seen:
                continue
            seen.add(child)
            pending.extend(calculation_children.get(child, ()))
        return len(seen & candidate_tags)

    totals = {key: 0 for key in TOTAL_TAG_MAP}
    sources = {}
    for total_key, priority_tags in TOTAL_TAG_MAP.items():
        candidates = {
            tag: raw_tags[tag]
            for tag in priority_tags
            if tag in raw_tags
        }
        if not candidates:
            continue
        candidate_tags = set(candidates)
        priority = {tag: index for index, tag in enumerate(priority_tags)}
        selected_tag = min(
            candidates,
            key=lambda tag: (
                -descendant_count(tag, candidate_tags),
                priority[tag],
            ),
        )
        totals[total_key] = candidates[selected_tag]
        sources[total_key] = {
            "tag": selected_tag,
            "value": candidates[selected_tag],
            "candidates": candidates,
        }
    return totals, sources


def _normalize_taxonomy_label(text):
    normalized = unicodedata.normalize("NFKC", str(text or "")).lower()
    normalized = re.sub(r"[\s\u3000,，・･()（）\[\]［］【】]", "", normalized)
    return normalized


def _preferred_taxonomy_labels(labels):
    def priority(label):
        role = (label.get("role") or "").lower().rstrip("/")
        role_rank = 0 if role.endswith("/label") else 1
        lang_rank = 0 if (label.get("lang") or "").lower().startswith("ja") else 1
        return role_rank, lang_rank, label.get("text", "")

    texts = []
    for label in sorted(labels or [], key=priority):
        text = _normalize_taxonomy_label(label.get("text"))
        if text and text not in texts:
            texts.append(text)
    standard = [
        _normalize_taxonomy_label(label.get("text"))
        for label in labels or []
        if (label.get("role") or "").lower().rstrip("/").endswith("/label")
    ]
    standard = [text for text in standard if text]
    return list(dict.fromkeys(standard or texts))


def classify_taxonomy_labels(labels, section=None):
    """Return unambiguous category hints from standard Japanese/English labels."""
    texts = _preferred_taxonomy_labels(labels)
    if not texts:
        return []
    sections = [section] if section else list(TAXONOMY_LABEL_CATEGORY_RULES)
    matches = {}
    for text in texts:
        if re.search(r"(?:合計|総計|subtotal|total)$", text):
            continue
        for target_section in sections:
            for pattern, category, action in TAXONOMY_LABEL_CATEGORY_RULES[target_section]:
                if re.search(pattern, text, flags=re.IGNORECASE):
                    matches.setdefault((target_section, category), {
                        "section": target_section,
                        "category": category,
                        "action": action,
                        "reason": "taxonomy_standard_label",
                        "confidence": 2,
                        "taxonomy_label": text,
                    })
                    break
    if len(matches) != 1:
        return []
    return list(matches.values())


def _taxonomy_labels_indicate_total(labels):
    return any(
        re.search(r"合計|総計|subtotal|total", text, flags=re.IGNORECASE)
        for text in _preferred_taxonomy_labels(labels)
    )


def _taxonomy_labels_indicate_noncarrying_component(labels):
    return any(
        re.search(
            r"取得原価|取得価額|減価償却累計|減損損失累計|"
            r"acquisitioncost|accumulateddepreciation|grosscarrying",
            text,
            flags=re.IGNORECASE,
        )
        for text in _preferred_taxonomy_labels(labels)
    )


def _taxonomy_label_section_anchor(labels):
    matched_sections = set()
    for text in _preferred_taxonomy_labels(labels):
        for section, patterns in TAXONOMY_LABEL_SECTION_PATTERNS.items():
            if any(re.search(pattern, text, flags=re.IGNORECASE) for pattern in patterns):
                matched_sections.add(section)
    if len(matched_sections) == 1:
        section = next(iter(matched_sections))
        return section, SEMANTIC_SECTION_SPECS[section]["other"]
    return None


def _taxonomy_anchor(parent, concept_labels=None):
    abstract_section = TAXONOMY_ABSTRACT_SECTION_ANCHORS.get(parent)
    if abstract_section:
        return abstract_section, SEMANTIC_SECTION_SPECS[abstract_section]["other"]
    total_section = TOTAL_TAG_LOOKUP.get(parent)
    if total_section in TAXONOMY_SECTION_TOTALS:
        return total_section, SEMANTIC_SECTION_SPECS[total_section]["other"]
    category = TAG_MAPPING.get(parent)
    section = _taxonomy_section_for_category(category) if category else None
    if section:
        return section, category
    labels = (concept_labels or {}).get(parent, [])
    section_anchor = _taxonomy_label_section_anchor(labels)
    if section_anchor:
        return section_anchor
    label_options = classify_taxonomy_labels(labels)
    if len(label_options) == 1:
        option = label_options[0]
        return option["section"], option["category"]
    return None


def find_taxonomy_anchors(
    tag, parent_index, selected_context=None, max_depth=6, concept_labels=None,
):
    """Find nearest known B/S ancestors without crossing link roles."""
    direct_edges = list(parent_index.get(tag, []))
    is_nonconsolidated = "NonConsolidated" in (selected_context or "")
    all_edges = [
        edge for edges in parent_index.values() for edge in edges
    ]
    has_consolidated_statement = any(
        _taxonomy_role_is_consolidated(edge.get("role", ""))
        for edge in all_edges
    )
    if is_nonconsolidated:
        direct_edges = [
            edge for edge in direct_edges
            if not _taxonomy_role_is_consolidated(edge["role"])
        ]
    else:
        consolidated_edges = [
            edge for edge in direct_edges
            if _taxonomy_role_is_consolidated(edge["role"])
        ]
        standalone_statement_edges = [
            edge for edge in direct_edges
            if (
                _taxonomy_role_is_nonconsolidated(edge["role"])
                or _taxonomy_role_is_standalone_statement(edge["role"])
            )
        ]
        if consolidated_edges:
            direct_edges = consolidated_edges
        elif has_consolidated_statement and standalone_statement_edges:
            direct_edges = []
        elif has_consolidated_statement:
            direct_edges = [
                edge for edge in direct_edges
                if edge.get("arcrole") == "general-special"
            ]
        else:
            direct_edges = [
                edge for edge in direct_edges
                if not _taxonomy_role_is_nonconsolidated(edge["role"])
            ]

    anchors = []
    for first in direct_edges:
        queue = [(first["parent"], 1, [first["parent"]])]
        visited = {tag}
        while queue:
            concept, depth, path = queue.pop(0)
            if concept in visited or depth > max_depth:
                continue
            visited.add(concept)
            anchor = _taxonomy_anchor(concept, concept_labels)
            if anchor:
                section, category = anchor
                anchors.append({
                    "section": section,
                    "category": category,
                    "anchor": concept,
                    "depth": depth,
                    "path": path,
                    "link_type": first["link_type"],
                    "arcrole": first.get("arcrole"),
                    "role": first["role"],
                })
                continue
            for edge in parent_index.get(concept, []):
                if (
                    edge["link_type"] == first["link_type"]
                    and edge["role"] == first["role"]
                ):
                    queue.append((edge["parent"], depth + 1, path + [edge["parent"]]))
    return anchors


def classify_taxonomy_bs_tag(
    tag, parent_index, raw_tags=None, selected_context=None, concept_labels=None,
):
    """Infer an unknown concept from its nearest known taxonomy ancestors."""
    raw_tags = raw_tags or {}
    if tag in TAG_MAPPING or tag in TOTAL_TAG_LOOKUP:
        return []
    if any(pattern in tag for pattern in SEMANTIC_TAG_EXCLUSION_PATTERNS):
        return []
    if tag.startswith("Total") or tag.endswith("Total") or _net_variant_exists(tag, raw_tags):
        return []
    tag_labels = (concept_labels or {}).get(tag, [])
    if (
        _taxonomy_labels_indicate_total(tag_labels)
        or _taxonomy_labels_indicate_noncarrying_component(tag_labels)
    ):
        return []

    anchors = find_taxonomy_anchors(
        tag, parent_index, selected_context, concept_labels=concept_labels,
    )
    if not anchors:
        return []

    evidence_by_section = {}
    for anchor in anchors:
        stats = evidence_by_section.setdefault(anchor["section"], {
            "anchors": [], "link_types": set(), "arcroles": set(), "score": 0,
        })
        stats["anchors"].append(anchor)
        stats["link_types"].add(anchor["link_type"])
        if anchor["link_type"] == "calculation":
            base = 7
        elif anchor.get("arcrole") == "general-special":
            base = 8
        elif anchor["link_type"] == "definition":
            base = 6
        else:
            base = 5
        if anchor.get("arcrole"):
            stats["arcroles"].add(anchor["arcrole"])
        stats["score"] = max(stats["score"], base - min(anchor["depth"] - 1, 3))
    for stats in evidence_by_section.values():
        if len(stats["link_types"]) > 1:
            stats["score"] += 3

    strong_sections = {
        section for section, stats in evidence_by_section.items()
        if (
            "calculation" in stats["link_types"]
            or "general-special" in stats["arcroles"]
        )
    }
    if len(strong_sections) > 1:
        return []

    ranked_sections = sorted(
        evidence_by_section.items(),
        key=lambda item: (-item[1]["score"], item[0]),
    )
    if len(ranked_sections) > 1 and ranked_sections[0][1]["score"] == ranked_sections[1][1]["score"]:
        return []
    section, stats = ranked_sections[0]

    semantic_options = [
        option for option in classify_unmapped_bs_tag(tag, raw_tags)
        if option["section"] == section
    ]
    label_options = classify_taxonomy_labels(
        tag_labels, section=section,
    )
    section_other = SEMANTIC_SECTION_SPECS[section]["other"]
    nearest = min(
        stats["anchors"],
        key=lambda item: (
            item["category"] == section_other,
            item["depth"],
            item["link_type"] != "calculation",
        ),
    )
    if label_options:
        categories = label_options
    elif semantic_options:
        categories = semantic_options
    else:
        category = nearest["category"]
        reason = "nearest_known_taxonomy_parent"
        if re.search(r"Provision|Allowance|Accrual|Reserve", tag):
            provision_categories = {
                "CurrentAssets": "流動_貸倒引当金",
                "NonCurrentAssets": "投資_貸倒引当金",
                "CurrentLiabilities": "流負_引当金",
                "NonCurrentLiabilities": "固負_引当金",
            }
            if section in provision_categories:
                category = provision_categories[section]
                reason = "taxonomy_section_provision_or_allowance"
        if re.search(r"Deposits?Received|DepositReceived", tag):
            deposit_categories = {
                "CurrentLiabilities": "流負_預り金",
                "NonCurrentLiabilities": "固負_長期預り金",
            }
            if section in deposit_categories:
                category = deposit_categories[section]
                reason = "taxonomy_section_deposit_received"
        categories = [{
            "section": section,
            "category": category,
            "reason": reason,
            "confidence": 1,
            "action": "add",
        }]
    support = "+".join(sorted(stats["link_types"]))
    return [{
        **option,
        "confidence": option.get("confidence", 1) + stats["score"],
        "reason": f"taxonomy_{support}:{nearest['anchor']}:{option['reason']}",
        "inference_source": "taxonomy",
        "taxonomy_anchor": nearest["anchor"],
        "taxonomy_path": nearest["path"],
        "taxonomy_link_types": sorted(stats["link_types"]),
        "taxonomy_arcroles": sorted(stats["arcroles"]),
        "taxonomy_labels": _preferred_taxonomy_labels(
            tag_labels,
        ),
    } for option in categories]


def _semantic_section_delta(summary, totals, section):
    spec = SEMANTIC_SECTION_SPECS[section]
    total = totals.get(section, 0)
    if not total:
        return None
    subtotal = sum(
        value for category, value in summary.items()
        if category.startswith(spec["prefix"]) and category != spec["other"]
    )
    return total - subtotal - summary.get(spec["other"], 0)


def reconcile_taxonomy_same_category_siblings(
    summary, totals, raw_tags, taxonomy_relationships, selected_context=None,
):
    """Add same-category lines only when calculation siblings close a section."""
    is_nonconsolidated = "NonConsolidated" in (selected_context or "")
    grouped = {}
    for edge in taxonomy_relationships or []:
        if edge.get("link_type") != "calculation":
            continue
        role = edge.get("role", "")
        if is_nonconsolidated and _taxonomy_role_is_consolidated(role):
            continue
        if not is_nonconsolidated and (
            _taxonomy_role_is_nonconsolidated(role)
            or _taxonomy_role_is_standalone_statement(role)
        ):
            continue
        child = edge.get("child")
        category = TAG_MAPPING.get(child)
        if child not in raw_tags or not category or category in ADDITIVE_CATS:
            continue
        grouped.setdefault((edge.get("parent"), category), set()).add(child)

    best_by_category = {}
    for (parent, category), children in grouped.items():
        if len(children) < 2:
            continue
        section = _taxonomy_section_for_category(category)
        before = _semantic_section_delta(summary, totals, section) if section else None
        if before is None:
            continue
        current = summary.get(category, 0)
        proposed = sum(raw_tags[child] for child in children)
        if proposed == current:
            continue
        after = before - (proposed - current)
        tolerance = max(abs(totals.get(section, 0)) * 0.0001, 1_000_000)
        if abs(after) + tolerance >= abs(before) * 0.25:
            continue
        candidate = (
            abs(after), parent or "", sorted(children), proposed, before, after,
        )
        if category not in best_by_category or candidate < best_by_category[category]:
            best_by_category[category] = candidate

    adjustments = []
    for category, candidate in best_by_category.items():
        _, parent, children, proposed, before, after = candidate
        previous = summary.get(category, 0)
        summary[category] = proposed
        adjustments.append({
            "category": category,
            "tag": "+".join(children),
            "value": proposed - previous,
            "reason": "calculation_siblings_require_same_category_addition",
            "taxonomy_parent": parent,
            "delta_before": before,
            "delta_after": after,
        })
    return adjustments


def reconcile_taxonomy_aggregate_overlaps(
    summary, totals, raw_tags, taxonomy_relationships, selected_context=None,
):
    """Replace a mapped aggregate when taxonomy relations and values prove overlap."""
    is_nonconsolidated = "NonConsolidated" in (selected_context or "")
    grouped = {}
    for edge in taxonomy_relationships or []:
        link_type = edge.get("link_type")
        arcrole = edge.get("arcrole")
        if link_type not in {"calculation", "definition", "presentation"}:
            continue
        if link_type == "definition" and arcrole != "domain-member":
            continue
        role = edge.get("role", "")
        if is_nonconsolidated and _taxonomy_role_is_consolidated(role):
            continue
        if not is_nonconsolidated and _taxonomy_role_is_nonconsolidated(role):
            continue
        parent = edge.get("parent")
        child = edge.get("child")
        if parent not in raw_tags or child not in raw_tags:
            continue
        if raw_tags[child] < 0:
            continue
        if link_type == "calculation":
            try:
                weight = float(edge.get("weight") or 1)
            except (TypeError, ValueError):
                continue
            if weight != 1:
                continue
        child_info = grouped.setdefault(parent, {}).setdefault(child, {
            "value": raw_tags[child],
            "link_types": set(),
            "roles": set(),
        })
        child_info["link_types"].add(link_type)
        child_info["roles"].add(role)

    adjustments = []
    processed = set()
    for parent, child_info in grouped.items():
        supported_children = {
            child: info
            for child, info in child_info.items()
            if (
                "calculation" in info["link_types"]
                or {"definition", "presentation"}.issubset(info["link_types"])
            )
        }
        child_values = {
            child: info["value"] for child, info in supported_children.items()
        }
        child_key = (parent, tuple(sorted(child_values)))
        if child_key in processed or len(child_values) < 2:
            continue
        processed.add(child_key)
        if parent not in TAG_MAPPING or any(child not in TAG_MAPPING for child in child_values):
            continue
        parent_category = TAG_MAPPING[parent]
        section = _taxonomy_section_for_category(parent_category)
        if (
            not section
            or parent_category == SEMANTIC_SECTION_SPECS[section]["other"]
            or parent_category in ADDITIVE_CATS
        ):
            continue

        parent_value = raw_tags[parent]
        children_total = sum(child_values.values())
        tolerance = max(1_000_000, abs(parent_value) * 0.001)
        if abs(parent_value - children_total) > tolerance:
            continue
        if abs(summary.get(parent_category, 0) - parent_value) > tolerance:
            continue

        child_summary = {key: 0 for key in summary}
        applied_children = []
        for child, value in child_values.items():
            if should_skip_item_tag(child, raw_tags):
                continue
            apply_mapped_tag(child_summary, child, value)
            applied_children.append(child)
        replacement = child_summary.get(parent_category, 0)
        before = _semantic_section_delta(summary, totals, section)
        if before is None or replacement == summary.get(parent_category, 0):
            continue
        original = summary[parent_category]
        summary[parent_category] = replacement
        after = _semantic_section_delta(summary, totals, section)
        if after is None or abs(after) + 1_000_000 >= abs(before):
            summary[parent_category] = original
            continue
        adjustments.append({
            "tag": parent,
            "category": parent_category,
            "value": replacement - original,
            "raw_value": parent_value,
            "reason": (
                "calculation_parent_replaced_by_mapped_children"
                if all(
                    "calculation" in info["link_types"]
                    for info in supported_children.values()
                )
                else "taxonomy_parent_replaced_by_mapped_children"
            ),
            "children": sorted(applied_children),
            "taxonomy_link_types": sorted({
                link_type
                for info in supported_children.values()
                for link_type in info["link_types"]
            }),
            "roles": sorted({
                role
                for info in supported_children.values()
                for role in info["roles"]
            }),
            "delta_before": before,
            "delta_after": after,
        })
    return adjustments


def reconcile_semantic_unmapped_tags(
    summary, totals, raw_tags, taxonomy_relationships=None, selected_context=None,
    taxonomy_labels=None,
):
    """Apply unknown concepts only when meaning and section totals both agree."""
    candidates_by_section = {section: [] for section in SEMANTIC_SECTION_SPECS}
    taxonomy_parent_index = build_taxonomy_parent_index(taxonomy_relationships)
    for tag, value in raw_tags.items():
        if abs(value) < 100_000_000:
            continue
        taxonomy_options = classify_taxonomy_bs_tag(
            tag, taxonomy_parent_index, raw_tags, selected_context,
            concept_labels=taxonomy_labels,
        )
        semantic_options = (
            [] if taxonomy_options else classify_unmapped_bs_tag(tag, raw_tags)
        )
        option_map = {
            (option["section"], option["category"]): option
            for option in semantic_options
        }
        for option in taxonomy_options:
            option_map[(option["section"], option["category"])] = option
        for option in option_map.values():
            current = summary.get(option["category"], 0)
            if option.get("action") == "max":
                effective_value = max(current, value) - current
            elif option.get("action") == "receivable_parent":
                represented = sum(summary.get(category, 0) for category in {
                    "流動_受取手形", "流動_売掛金", "流動_契約資産",
                    "流動_受取手形・売掛金(合算)",
                })
                if "Electronically" in tag:
                    represented += summary.get("流動_電子記録債権", 0)
                effective_value = value - represented
            else:
                effective_value = value
            if abs(effective_value) < 100_000_000:
                continue
            candidates_by_section[option["section"]].append({
                **option, "tag": tag, "value": value,
                "effective_value": effective_value,
            })

    adjustments = []
    applied_tags = set()
    for section in SEMANTIC_SECTION_SPECS:
        delta_before = _semantic_section_delta(summary, totals, section)
        if delta_before is None or abs(delta_before) < 100_000_000:
            continue
        total = totals[section]
        tolerance = min(max(abs(total) * 0.001, 100_000_000), 1_000_000_000)
        candidates = [
            item for item in candidates_by_section[section]
            if item["tag"] not in applied_tags
            and abs(item["effective_value"]) <= abs(delta_before) * 2 + tolerance
        ]
        candidates.sort(
            key=lambda item: abs(abs(item["effective_value"]) - abs(delta_before))
        )
        candidates = candidates[:14]

        best = None
        for size in range(1, min(4, len(candidates)) + 1):
            for combo in combinations(candidates, size):
                tags = [item["tag"] for item in combo]
                if len(tags) != len(set(tags)):
                    continue
                trial = dict(summary)
                for item in combo:
                    if item.get("action") in {"max", "receivable_parent"}:
                        trial[item["category"]] = max(
                            trial.get(item["category"], 0), item["value"]
                        )
                    else:
                        trial[item["category"]] = (
                            trial.get(item["category"], 0) + item["value"]
                        )
                if any(
                    item["category"] == "流動_受取手形・売掛金(合算)"
                    for item in combo
                ):
                    reconcile_receivable_presentation(trial, totals, raw_tags)
                duplicate_adjustments = reconcile_optional_duplicate_categories(trial, totals)
                delta_after = _semantic_section_delta(trial, totals, section)
                rank = (
                    abs(delta_after),
                    len(combo),
                    -sum(item["confidence"] for item in combo),
                )
                if best is None or rank < best[0]:
                    best = (rank, trial, combo, duplicate_adjustments, delta_after)

        if best is None:
            continue
        _, trial, combo, duplicate_adjustments, delta_after = best
        improvement = abs(delta_before) - abs(delta_after)
        if (
            improvement < max(100_000_000, abs(delta_before) * 0.7)
            or abs(delta_after) > max(tolerance, abs(delta_before) * 0.2)
        ):
            continue

        summary.clear()
        summary.update(trial)
        for item in combo:
            applied_tags.add(item["tag"])
            inference_source = item.get("inference_source", "semantic")
            adjustments.append({
                "tag": item["tag"],
                "category": item["category"],
                "value": item["effective_value"],
                "raw_value": item["value"],
                "reason": f"{inference_source}_fallback:{item['reason']}",
                "confidence": item["confidence"],
                "delta_before": delta_before,
                "delta_after": delta_after,
                "inference_source": inference_source,
                "taxonomy_anchor": item.get("taxonomy_anchor"),
                "taxonomy_path": item.get("taxonomy_path"),
                "taxonomy_link_types": item.get("taxonomy_link_types"),
                "taxonomy_arcroles": item.get("taxonomy_arcroles"),
                "taxonomy_label": item.get("taxonomy_label"),
                "taxonomy_labels": item.get("taxonomy_labels"),
            })
        for item in duplicate_adjustments:
            adjustments.append({
                **item,
                "reason": f"semantic_fallback_triggered:{item['reason']}",
            })
    return adjustments, applied_tags


def reconcile_skipped_section_summaries(summary, totals, raw_tags):
    """Restore only the unrepresented remainder of skipped parent summaries."""
    adjustments = []
    candidate_specs = [
        (
            "PropertyPlantAndEquipmentIFRS",
            "有形_その他有形固定資産",
            lambda key: key.startswith("有形_") and key not in {
                "有形_リース資産", "有形_減価償却累計額",
            },
        ),
        (
            "PropertyPlantAndEquipment",
            "有形_その他有形固定資産",
            lambda key: key.startswith("有形_")
            and key != "有形_減価償却累計額",
        ),
        (
            "IntangibleAssetsIFRS",
            "無形_その他無形固定資産",
            lambda key: key.startswith("無形_") and key != "無形_のれん",
        ),
        (
            "InvestmentsAndOtherAssets",
            "投資_その他固定資産",
            lambda key: key.startswith("投資_"),
        ),
        (
            "PlantAndEquipmentAndIntangibleAssetsELE",
            "有形_その他有形固定資産",
            lambda key: key.startswith(("有形_", "無形_")) and key != "有形_減価償却累計額",
        ),
    ]
    total = totals.get("NonCurrentAssets", 0)
    if total > 0:
        subtotal = sum(
            amount for key, amount in summary.items()
            if key.startswith(("有形_", "無形_", "投資_"))
        )
        delta_before = total - subtotal
        tolerance = max(abs(total) * 0.0001, 1_000_000)
        candidates = []
        for tag, category, is_component in candidate_specs:
            parent_value = raw_tags.get(tag, 0)
            if parent_value <= 0:
                continue
            represented = sum(
                max(amount, 0) for key, amount in summary.items()
                if is_component(key)
            )
            remainder = parent_value - represented
            if remainder > tolerance:
                candidates.append((tag, category, remainder, represented, parent_value))

        best = None
        for mask in range(1, 1 << len(candidates)):
            selected = [
                candidate for index, candidate in enumerate(candidates)
                if mask & (1 << index)
            ]
            delta_after = delta_before - sum(item[2] for item in selected)
            candidate = (abs(delta_after), len(selected), delta_after, selected)
            if best is None or candidate[:2] < best[:2]:
                best = candidate

        if best is not None:
            _, _, delta_after, selected = best
            if abs(delta_after) + tolerance < abs(delta_before) * 0.25:
                for tag, category, remainder, represented, parent_value in selected:
                    summary[category] = summary.get(category, 0) + remainder
                    adjustments.append({
                        "category": category,
                        "tag": tag,
                        "value": remainder,
                        "parent_value": parent_value,
                        "represented_value": represented,
                        "reason": "section_total_supports_skipped_summary_remainder",
                        "delta_before": delta_before,
                        "delta_after": delta_after,
                    })

    total = totals.get("NonCurrentAssets", 0)
    aggregate_accumulated_tags = (
        "AccumulatedDepreciationPPEByGroup",
        "AccumulatedImpairmentLossPPEByGroup",
        "AccumulatedDepreciationAndImpairmentLossPPEByGroup",
    )
    aggregate_candidates = [
        (tag, raw_tags[tag]) for tag in aggregate_accumulated_tags
        if raw_tags.get(tag, 0) < 0
    ]
    if aggregate_candidates and total > 0:
        subtotal = sum(
            amount for key, amount in summary.items()
            if key.startswith(("有形_", "無形_", "投資_"))
        )
        delta_before = total - subtotal
        tolerance = max(abs(total) * 0.0001, 1_000_000)
        best = None
        for size in range(1, len(aggregate_candidates) + 1):
            for combo in combinations(aggregate_candidates, size):
                tags = {tag for tag, _ in combo}
                if (
                    "AccumulatedDepreciationAndImpairmentLossPPEByGroup" in tags
                    and len(tags) > 1
                ):
                    continue
                combined_value = sum(value for _, value in combo)
                delta_after = delta_before - combined_value
                rank = (abs(delta_after), size)
                if best is None or rank < best[0]:
                    best = (rank, combo, combined_value, delta_after)
        if best and abs(best[3]) + tolerance < abs(delta_before) * 0.25:
            _, selected, value, delta_after = best
            category = "有形_減価償却累計額"
            summary[category] = summary.get(category, 0) + value
            adjustments.append({
                "category": category,
                "tag": "+".join(tag for tag, _ in selected),
                "value": value,
                "reason": "section_total_supports_aggregate_depreciation_or_impairment",
                "delta_before": delta_before,
                "delta_after": delta_after,
            })
    return adjustments


def reconcile_parent_component_overlaps(summary, totals, raw_tags):
    """Remove a component only when a reported parent total proves it is duplicated."""
    adjustments = []
    parent = raw_tags.get("PropertyPlantAndEquipmentIFRS", 0)
    if parent <= 0:
        return adjustments

    categories = {
        key: value for key, value in summary.items()
        if key.startswith("有形_") and value > 0
    }
    subtotal = sum(categories.values())
    delta_before = parent - subtotal
    tolerance = max(abs(parent) * 0.001, 1_000_000)
    if delta_before >= -tolerance:
        return adjustments

    noncurrent_total = totals.get("NonCurrentAssets", 0)
    noncurrent_subtotal = sum(
        amount for key, amount in summary.items()
        if key.startswith(("有形_", "無形_", "投資_"))
    )
    section_delta_before = noncurrent_total - noncurrent_subtotal

    best = None
    for category, value in categories.items():
        delta_after = delta_before + value
        if abs(delta_after) + tolerance >= abs(delta_before) * 0.25:
            continue
        section_delta_after = section_delta_before + value
        if abs(section_delta_after) + tolerance >= abs(section_delta_before) * 0.9:
            continue
        candidate = (
            abs(delta_after), category, value, delta_after, section_delta_after
        )
        if best is None or candidate < best:
            best = candidate

    if best is None:
        return adjustments

    _, category, value, delta_after, section_delta_after = best
    summary[category] = 0
    adjustments.append({
        "category": category,
        "tag": "PropertyPlantAndEquipmentIFRS",
        "value": value,
        "reason": "parent_total_indicates_duplicate_component",
        "delta_before": delta_before,
        "delta_after": delta_after,
        "section_delta_before": section_delta_before,
        "section_delta_after": section_delta_after,
    })
    return adjustments


